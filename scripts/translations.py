def load_source_names():
    # Keep first-appearance order from the original metadata; no private helper file required.
    data = json.load(open(P("poses.json"), encoding="utf-8"))
    names = list(dict.fromkeys(d["ポーズ名"] for d in data))
    cats = list(dict.fromkeys((d.get("分類") or "").strip() for d in data))
    return names, cats


def main():
    names, cats = load_source_names()
    print(f"源文件: 姿势名 {len(names)} 条 / 分类 {len(cats)} 条")
    assert len(POSES_ZH) == len(names), f"译文条数 {len(POSES_ZH)} != 源 {len(names)}"
